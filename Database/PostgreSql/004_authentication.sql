BEGIN;

ALTER TABLE "USERS"
  ADD COLUMN IF NOT EXISTS "USERNAME" VARCHAR(200);

ALTER TABLE "USERS"
  ALTER COLUMN "PHONE" DROP NOT NULL;

DROP INDEX IF EXISTS "UK_USERS_USERNAME_CI";
CREATE UNIQUE INDEX IF NOT EXISTS "UK_USERS_USERNAME"
  ON "USERS" ("USERNAME");

CREATE TABLE IF NOT EXISTS "AUTH_SESSIONS" (
  "ID" UUID NOT NULL,
  "USER_ID" UUID NOT NULL,
  "CONTEXT" VARCHAR(20) NOT NULL,
  "TOKEN_HASH" CHAR(64) NOT NULL,
  "CREATED_AT" TIMESTAMPTZ(6) NOT NULL,
  "EXPIRES_AT" TIMESTAMPTZ(6) NOT NULL,
  "REVOKED_AT" TIMESTAMPTZ(6) NULL,
  CONSTRAINT "PK_AUTH_SESSIONS" PRIMARY KEY ("ID"),
  CONSTRAINT "UK_AUTH_SESSIONS_TOKEN_HASH" UNIQUE ("TOKEN_HASH"),
  CONSTRAINT "CK_AUTH_SESSIONS_CONTEXT" CHECK ("CONTEXT" IN ('ADMIN', 'USER')),
  CONSTRAINT "CK_AUTH_SESSIONS_EXPIRY" CHECK ("EXPIRES_AT" > "CREATED_AT"),
  CONSTRAINT "FK_AUTH_SESSIONS_USER" FOREIGN KEY ("USER_ID") REFERENCES "USERS" ("ID")
);

CREATE INDEX IF NOT EXISTS "IX_AUTH_SESSIONS_USER_ID"
  ON "AUTH_SESSIONS" ("USER_ID");

CREATE INDEX IF NOT EXISTS "IX_AUTH_SESSIONS_ACTIVE_EXPIRY"
  ON "AUTH_SESSIONS" ("EXPIRES_AT")
  WHERE "REVOKED_AT" IS NULL;

