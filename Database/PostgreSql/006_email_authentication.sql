BEGIN;

CREATE UNIQUE INDEX IF NOT EXISTS "UK_USERS_EMAIL_CI"
  ON "USERS" (LOWER("EMAIL"))
  WHERE "EMAIL" IS NOT NULL;

CREATE TABLE IF NOT EXISTS "ADMIN_ACCOUNT_REQUESTS" (
  "ID" UUID NOT NULL,
  "USERNAME" VARCHAR(200) NOT NULL,
  "DISPLAY_NAME" VARCHAR(1000) NOT NULL,
  "EMAIL" VARCHAR(1000) NOT NULL,
  "STATUS" VARCHAR(30) NOT NULL,
  "REQUESTED_AT" TIMESTAMPTZ(6) NOT NULL,
  "REVIEWED_BY_USER_ID" UUID NULL,
  "REVIEWED_AT" TIMESTAMPTZ(6) NULL,
  CONSTRAINT "PK_ADMIN_ACCOUNT_REQUESTS" PRIMARY KEY ("ID"),
  CONSTRAINT "CK_ADMIN_ACCOUNT_REQUESTS_STATUS"
    CHECK ("STATUS" IN ('PENDING', 'APPROVED', 'REJECTED')),
  CONSTRAINT "FK_ADMIN_ACCOUNT_REQUESTS_REVIEWER"
    FOREIGN KEY ("REVIEWED_BY_USER_ID") REFERENCES "USERS" ("ID")
);

CREATE UNIQUE INDEX IF NOT EXISTS "UK_ADMIN_ACCOUNT_REQUESTS_PENDING_EMAIL_CI"
  ON "ADMIN_ACCOUNT_REQUESTS" (LOWER("EMAIL"))
  WHERE "STATUS" = 'PENDING';

CREATE UNIQUE INDEX IF NOT EXISTS "UK_ADMIN_ACCOUNT_REQUESTS_PENDING_USERNAME_CI"
  ON "ADMIN_ACCOUNT_REQUESTS" (LOWER("USERNAME"))
  WHERE "STATUS" = 'PENDING';

CREATE TABLE IF NOT EXISTS "AUTH_EMAIL_CHALLENGES" (
  "ID" UUID NOT NULL,
  "USER_ID" UUID NOT NULL,
  "PURPOSE" VARCHAR(40) NOT NULL,
  "SECRET_HASH" VARCHAR(1000) NOT NULL,
  "CREATED_AT" TIMESTAMPTZ(6) NOT NULL,
  "EXPIRES_AT" TIMESTAMPTZ(6) NOT NULL,
  "CONSUMED_AT" TIMESTAMPTZ(6) NULL,
  "FAILED_ATTEMPTS" INTEGER NOT NULL DEFAULT 0,
  CONSTRAINT "PK_AUTH_EMAIL_CHALLENGES" PRIMARY KEY ("ID"),
  CONSTRAINT "FK_AUTH_EMAIL_CHALLENGES_USER"
    FOREIGN KEY ("USER_ID") REFERENCES "USERS" ("ID"),
  CONSTRAINT "CK_AUTH_EMAIL_CHALLENGES_PURPOSE"
    CHECK ("PURPOSE" IN ('ADMIN_INVITATION', 'USER_EMAIL_VERIFICATION')),
  CONSTRAINT "CK_AUTH_EMAIL_CHALLENGES_EXPIRY"
    CHECK ("EXPIRES_AT" > "CREATED_AT"),
  CONSTRAINT "CK_AUTH_EMAIL_CHALLENGES_FAILED_ATTEMPTS"
    CHECK ("FAILED_ATTEMPTS" >= 0)
);

CREATE INDEX IF NOT EXISTS "IX_AUTH_EMAIL_CHALLENGES_ACTIVE"
  ON "AUTH_EMAIL_CHALLENGES" ("USER_ID", "PURPOSE", "EXPIRES_AT")
  WHERE "CONSUMED_AT" IS NULL;

COMMIT;
